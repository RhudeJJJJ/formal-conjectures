#!/usr/bin/env python3
"""Independent evidence audit for the new Spectrum1715 proof source.

Uses the pre-run source capture, not the old original-source success checker.
No Lean receipts or proofs are generated by this program.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path, PurePosixPath
import re
import zipfile

from rg_middle_residual_batch_authenticate_20261109 import (
    ALLOWED, NAMED, atomic_json, decode, payloads, read, require, sha,
    source_profile_names, table, without_comments,
)
from module_outputs import output_members

CAPTURE = Path(__file__).resolve().parent
REPOSITORY = "RhudeJJJJ/formal-conjectures"
BRANCH = "rg-middle-spectrum1715-split-20261109"
ENDPOINT = "Proofs.RadenkovicGutmanDegreeOneMiddleResidualSpectrum1715"
JOB_NAME = "spectrum1715-sample-split"
PIN = "0df444a360eaa60ab8c11dca51a86af692955474"
LC = "621a43d7cf21f87872392a01e874f2f1dbddc926"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--output-report", type=Path, required=True)
    parser.add_argument("--output-manifest", type=Path, required=True)
    args = parser.parse_args()
    evidence = args.evidence
    capture = read(CAPTURE / "source_preflight.json")
    closure_capture = read(CAPTURE / "closure_capture.json")
    candidate = read(CAPTURE / "rg_middle_spectrum1715_split_candidate_20261109.json")
    original_inventory = read(CAPTURE / "rg_middle_residual_batch_inventory_20261109.json")
    candidate_row = candidate["modules"][0]
    require(candidate_row["module"] == ENDPOINT and len(candidate["modules"]) == 1,
            "Wrong candidate module")
    require(candidate["mathlib"] == PIN and candidate["leancert"] == LC
            and candidate["lean_version"] == "4.33.1", "Changed candidate pins")
    require(sha((CAPTURE / "rg_middle_residual_batch_inventory_20261109.json").read_bytes())
            == candidate["original_inventory_sha256"], "Original inventory changed")
    sources = closure_capture["sources"]
    required = set(sources)
    require(len(required) == 19 and ENDPOINT in required, "Wrong source closure")
    prior_rows = table(original_inventory["expected_prior_rows"])
    require(len(prior_rows) == 707 and ENDPOINT not in prior_rows,
            "Wrong prior diagnostic scope")
    require(required - {ENDPOINT} <= set(prior_rows), "Missing required prior")
    require({n: prior_rows[n] for n in required - {ENDPOINT}}
            == closure_capture["expected_required_prior_rows"], "Prior capture changed")
    run = read(evidence / "run.json")
    jobs = read(evidence / "jobs.json")
    catalog = read(evidence / "artifacts.json")
    native_log = (evidence / "job.log").read_text()
    require(run["id"] == capture["expected_run_id"]
            and run["head_sha"] == capture["expected_head_sha"], "Wrong native run/head")
    require(run["repository"]["full_name"] == REPOSITORY and run["event"] == "push"
            and run["head_branch"] == BRANCH
            and run["path"] == ".github/workflows/" + BRANCH + ".yml",
            "Wrong repository, trigger or workflow")
    require(run["status"] in ("in_progress", "completed"), "Native run not started")
    matches = [j for j in jobs["jobs"] if j["name"] == JOB_NAME]
    require(len(matches) == 1, "Missing or ambiguous pilot job")
    job = matches[0]
    require(job["run_id"] == run["id"] and job["run_attempt"] == run["run_attempt"]
            and job["head_sha"] == run["head_sha"] and job["head_branch"] == BRANCH,
            "Native job identity differs")
    require(job["status"] == "completed" and job["conclusion"] == "success"
            and job["completed_at"], "Pilot job did not succeed")
    require(job["steps"] and all(s["status"] == "completed" and s["conclusion"] == "success"
                                for s in job["steps"]), "Unsuccessful pilot step")
    artifacts = [a for a in catalog["artifacts"]
                 if a["name"] == BRANCH + "-" + str(run["id"])]
    require(len(artifacts) == 1, "Missing or ambiguous pilot artifact")
    artifact = artifacts[0]
    require(artifact["expired"] is False and artifact["workflow_run"]["id"] == run["id"]
            and artifact["workflow_run"]["head_sha"] == run["head_sha"],
            "Artifact producer differs")
    zip_path = evidence / "artifact.zip"
    with zip_path.open("rb") as stream:
        archive_hash = hashlib.file_digest(stream, "sha256").hexdigest()
    require(artifact["digest"] == "sha256:" + archive_hash
            and artifact["size_in_bytes"] == zip_path.stat().st_size, "Artifact bytes differ")
    require(archive_hash in native_log and str(artifact["id"]) in native_log,
            "Native artifact upload binding absent")
    logged = table(payloads(native_log, "COMPLETED_MODULE_JSON "))
    require(set(logged) == {ENDPOINT}, "Wrong native fresh frontier")
    fresh_row = logged[ENDPOINT]
    require(fresh_row["mode"] == "FRESH_KERNEL_EXPORT" and "origin" not in fresh_row
            and "transport_capsule" not in fresh_row, "Fresh provenance rewritten")
    require(type(fresh_row["seconds"]) in (int, float)
            and math.isfinite(fresh_row["seconds"]) and 0 <= fresh_row["seconds"] <= 600,
            "Fresh duration exceeds unchanged module timeout")
    require(payloads(native_log, "RETAINED_RECORD_COUNTS ") == [{"total": 708, "fresh": 1}],
            "Wrong retained diagnostic frontier")
    with zipfile.ZipFile(zip_path) as archive:
        output_specs = list(output_members(ENDPOINT, fresh_row))
        expected_members = {"generated_source/" + row["path"] for row in sources.values()}
        expected_members.update("frozen_validation/" + name
                                for name in capture["frozen_files_sha256"])
        expected_members.update({"generated_source/generated_source_manifest.json",
                                 "diagnostics_records.json", "receipt.json", "resource_observer.json",
                                 ENDPOINT + ".json", ENDPOINT + ".log"})
        expected_members.update(spec[0] for spec in output_specs)
        members = archive.namelist()
        require(len(members) == len(set(members)) and set(members) == expected_members,
                "Unexpected complete archive scope")
        for name in members:
            p = PurePosixPath(name)
            require(not p.is_absolute() and ".." not in p.parts and "\\" not in name
                    and not archive.getinfo(name).is_dir(), "Unsafe archive member")
        frozen = {}
        for name, digest in capture["frozen_files_sha256"].items():
            raw = archive.read("frozen_validation/" + name)
            require(raw == (CAPTURE / name).read_bytes() and sha(raw) == digest,
                    "Frozen candidate/validator differs: " + name)
            frozen[name] = digest
        hashes, dependencies, closures = {}, {}, {}
        for name, entry in sources.items():
            raw = archive.read("generated_source/" + entry["path"])
            require(raw == (CAPTURE / "sources" / entry["path"]).read_bytes()
                    and sha(raw) == entry["sha256"], "Captured source differs: " + name)
            code = without_comments(raw.decode())
            require(not re.search(r"\b(sorry|admit|native_decide)\b|^\s*axiom\s", code, re.M),
                    "Admission or unchecked native proof: " + name)
            hashes[name] = sha(raw)
            dependencies[name] = sorted(set(re.findall(
                r"^\s*(?:public\s+)?import\s+((?:Proofs|LeanCert)\.[\w.]+)\s*$", code, re.M)))
            require(set(dependencies[name]) <= required, "Source dependency missing")
            if name == ENDPOINT:
                require(source_profile_names(code) == candidate_row["ordered_axiom_names"],
                        "Candidate profile declarations differ")
        visiting = set()
        def closure(name):
            if name not in closures:
                require(name not in visiting, "Cyclic source imports")
                visiting.add(name)
                closures[name] = sha(json.dumps([name, hashes[name], PIN, LC,
                    [(dep, closure(dep)) for dep in dependencies[name]]], separators=(",", ":")).encode())
                visiting.remove(name)
            return closures[name]
        closure(ENDPOINT)
        require(set(closures) == required and closures == closure_capture["source_closure_sha256"],
                "Dependency closure differs")
        require(hashes[ENDPOINT] == candidate_row["candidate_source_sha256"]
                and closures[ENDPOINT] == candidate_row["candidate_source_closure_sha256"],
                "New candidate identity differs")
        source_manifest = decode(archive.read("generated_source/generated_source_manifest.json"))
        expected_source_manifest = {
            "kind": "SAME_ORIGINAL_PROPOSITIONS_SAMPLE_SPLIT_NEW_SOURCE_IDENTITY",
            "endpoint": ENDPOINT, "original_source_commit": candidate["original_source_commit"],
            "source_sha256": {entry["path"]: entry["sha256"] for entry in sources.values()},
            "source_closure_sha256": closures, "source_count": 19,
            "expected_prior_count": 18, "expected_fresh_count": 1,
            "original_statements_and_numerical_data_unchanged": True,
            "status": "SOURCE_ONLY_REQUIRES_FRESH_NATIVE_KERNEL_RECEIPT"}
        require(source_manifest == expected_source_manifest, "Wrong full source manifest")
        diagnostics = table(decode(archive.read("diagnostics_records.json"))["modules"])
        require(set(diagnostics) == set(prior_rows) | {ENDPOINT}, "Wrong diagnostic scope")
        require(all(diagnostics[n] == row for n, row in prior_rows.items()),
                "Inherited origin/record changed")
        receipt_raw = archive.read("receipt.json")
        receipt = decode(receipt_raw)
        require(receipt["scope"] == "EXPLICIT_EXTENSION_CLOSURE"
                and receipt["endpoints"] == [ENDPOINT], "Wrong native receipt scope")
        require(receipt["mathlib"] == PIN and receipt["leancert"] == LC
                and "version 4.33.1," in receipt["lean"], "Receipt dependency pins differ")
        require(receipt["global_rg"] == "NOT_PROVED"
                and receipt["complete_submission"] == "NOT_SUBMITTED", "Overstated receipt")
        rows = table(receipt["modules"])
        require(set(rows) == required and all(rows[n] == diagnostics[n] for n in required),
                "Receipt incomplete or inconsistent")
        for name, row in rows.items():
            require(row["source_sha256"] == hashes[name]
                    and row["source_closure_sha256"] == closures[name], "Receipt source identity differs")
            require(row["axiom_profiles"] and all(set(p) <= ALLOWED for p in row["axiom_profiles"]),
                    "Unapproved axiom profile")
        require(rows[ENDPOINT] == fresh_row == decode(archive.read(ENDPOINT + ".json")),
                "Native/archive fresh row differs")
        output_bytes = 0
        output_hashes = {}
        for path, digest, size in output_specs:
            raw = archive.read(path)
            require(sha(raw) == digest and (size is None or len(raw) == size),
                    "Compiled object bytes differ")
            output_bytes += len(raw)
            output_hashes[path] = {"sha256": digest, "bytes": len(raw)}
        module_log = archive.read(ENDPOINT + ".log").decode()
        require(not re.search(r"\b(error|warning)(?:\([^\n]*?\))?:", module_log),
                "Candidate module warning/error")
        matches = list(NAMED.finditer(module_log))
        names = [m[1] for m in matches]
        require(names == candidate_row["ordered_axiom_names"] and len(names) == 23,
                "Wrong ordered named axiom profiles")
        profiles = [sorted(set(a.strip() for a in (m[2] or "").split(",") if a.strip()))
                    for m in matches]
        require(all(set(p) <= ALLOWED for p in profiles), "Unapproved candidate axiom")
        grouped = [p for m, p in zip(matches, profiles) if m[2] is not None]
        grouped += [p for m, p in zip(matches, profiles) if m[2] is None]
        require(grouped == fresh_row["axiom_profiles"], "Named/logged profile mismatch")
        kernel_pass = dict(expected_source_manifest)
        kernel_pass["status"] = "FRESH_NATIVE_KERNEL_RECEIPT_CHECKED_FOR_NEW_SOURCE"
        kernel_pass["named_axiom_profiles"] = names
        require(payloads(native_log, "SPECTRUM1715_SPLIT_KERNEL_PASS ") == [kernel_pass],
                "Native source-specific completion missing")
        resource = decode(archive.read("resource_observer.json"))
        require(payloads(native_log, "RG_KERNEL_RESOURCE_RESULT ")
                == [{k: v for k, v in resource.items() if k != "samples"}],
                "Resource result differs")
        require(payloads(native_log, "RG_KERNEL_RESOURCE_OBSERVATION ") == resource["samples"],
                "Resource samples differ")
        require(resource["status"] == "VERIFIER_COMPLETED" and resource["exit_code"] == 0
                and resource["mathlib_and_lean_flags_unchanged"] is True and resource["samples"],
                "Verifier/resource completion absent")
        require(not payloads(native_log, "RG_KERNEL_RESOURCE_GUARD_LOW_MEMORY "),
                "Memory guard stopped verifier")
        require(all(type(s["available_bytes"]) is int and s["available_bytes"] >= 2048 * 1024**2
                    for s in resource["samples"] if s["lean_processes"]),
                "Observed memory reserve violation")
        require(resource["maximum_aggregate_lean_rss"] >= max(s["aggregate_lean_rss"]
                    for s in resource["samples"]), "Invalid resource maximum")
    restore = {"repository": REPOSITORY, "run": run["id"], "job": job["id"],
               "source_commit": run["head_sha"], "artifact_id": artifact["id"],
               "artifact_sha256": archive_hash, "mathlib": PIN, "lean_version": "4.33.1",
               "modules": {ENDPOINT: fresh_row}}
    report = {
        "status": "NEW_SOURCE_SPECTRUM1715_SPLIT_KERNEL_EXPORT_AUTHENTICATED",
        "repository": REPOSITORY, "run": run["id"], "job": job["id"],
        "source_commit": run["head_sha"], "original_source_commit": candidate["original_source_commit"],
        "artifact": {k: artifact[k] for k in ["id", "name", "size_in_bytes", "digest"]},
        "archive_members": len(members), "required_sources": 19, "required_prior_modules": 18,
        "fresh_modules": 1, "diagnostic_prior_rows": 707, "diagnostic_rows": 708,
        "named_axiom_profiles": [{"declaration": name, "axioms": p} for name, p in zip(names, profiles)],
        "candidate_source_sha256": hashes[ENDPOINT], "candidate_source_closure_sha256": closures[ENDPOINT],
        "original_propositions_and_numerical_data_preserved": True,
        "new_source_identity_not_original_15d45_object": True,
        "compiled_outputs": output_hashes, "compiled_output_bytes": output_bytes,
        "receipt_sha256": sha(receipt_raw), "frozen_validation": frozen,
        "resource_seconds": resource["seconds"], "peak_lean_rss_bytes": resource["maximum_aggregate_lean_rss"],
        "authenticator_sha256": sha(Path(__file__).read_bytes()),
        "source_preflight_sha256": sha((CAPTURE / "source_preflight.json").read_bytes()),
        "native_capture_sha256": {name: sha((evidence / name).read_bytes())
                                  for name in ["run.json", "jobs.json", "artifacts.json", "job.log"]},
        "old_batch024_certified": False, "new_residual_key_membership_proved": False,
        "middle_family_complete": False, "global_rg_proved": False,
        "kernel_receipt_created_by_authenticator": False,
        "prior_artifact_bytes_redownloaded_by_authenticator": False,
        "boundary": "One changed-source spectral module proves the same five original declarations. Downstream source closures must be rebuilt; no original batch or family completion follows."}
    atomic_json(args.output_manifest, restore)
    report["restore_manifest_sha256"] = sha(args.output_manifest.read_bytes())
    atomic_json(args.output_report, report)
    print(json.dumps({k: report[k] for k in ["status", "run", "job", "artifact", "required_sources",
          "required_prior_modules", "fresh_modules", "compiled_output_bytes", "resource_seconds",
          "peak_lean_rss_bytes", "restore_manifest_sha256"]}, indent=2))


if __name__ == "__main__":
    main()
