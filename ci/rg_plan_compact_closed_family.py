"""Plan/check two existing original closed families with sealed fresh frontiers.

The final degree-one-large planner keeps its default three-module allowlist.
This separate caller only permits the two unjoined degree-one-small wrappers;
the complete small-ge-four endpoint must be restored entirely from originals.
"""
import argparse
import hashlib
import json
import pathlib
import subprocess
import sys

import rg_plan_exact_degree_one_large as exact

ROOT = pathlib.Path(__file__).resolve().parents[1]
REGISTRIES = {
    'ci/rg_compact_closed_families_source_registry.json': '6239e2f99f5a8e23e77a61a9888d900c262104106bd49db8d881f8394e003b1a',
    'ci/rg_compact_finite_source_registry.json': '82f833a1aef6c294e55593092adf0d4c71013f2ec4012bcbe7a4266249f6b058',
    'ci/rg_materialize_compact_closed_families.py': 'e4a36a23aa882d9dc7c798a02336bdc46044b082536f78a5567f8dd25fec8a7a',
}
FAMILIES = {
    'degree_one_small': {
        'endpoint': 'Proofs.RadenkovicGutmanCompactFiniteOriginalDegreeOneSmall',
        'original_field': 'OriginalDegreeOneSmall.input_family',
        'required_modules': 4856,
        'source_sha256': '5c0836982b637f13813fac505d99e89ab566358623ff5af3afec1835e8ed26ed',
        'source_closure_sha256': 'a101da1472cbb6c3b2b1e72bf13315af80eac7aeb4f07cc1834b2739bef4869d',
        'fresh': {
            'Proofs.RadenkovicGutmanCompactFiniteDegreeOneSmallCertificatesComplete',
            'Proofs.RadenkovicGutmanCompactFiniteOriginalDegreeOneSmall',
        },
    },
    'small_ge_four': {
        'endpoint': 'Proofs.RadenkovicGutmanCompactFiniteOriginalSmallGeFour',
        'original_field': 'OriginalSmallGeFour.input_family',
        'required_modules': 669,
        'source_sha256': '3da3b0b09edb2502dd40f3b6a774ec995dfc2eb80d5f68915f99640e9c919cc5',
        'source_closure_sha256': '517fb9e3ea30f53c8173d27bf23caf1e09f2013f76da12d98f50a6809be77727',
        'fresh': set(),
    },
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--family', choices=sorted(FAMILIES), required=True)
    parser.add_argument('--phase', choices=('plan', 'check'), default='plan')
    parser.add_argument('--output', type=pathlib.Path, required=True)
    parser.add_argument('--build-directory', type=pathlib.Path)
    args = parser.parse_args()
    config = FAMILIES[args.family]
    for relative, digest in REGISTRIES.items():
        assert hashlib.sha256((ROOT / relative).read_bytes()).hexdigest() == digest, relative

    if args.phase == 'check':
        assert args.build_directory is not None
        plan = json.loads(args.output.read_bytes())
        receipt = json.loads((args.build_directory / 'receipt.json').read_bytes())
        assert plan['compact_family'] == args.family
        assert plan['complete_original_object_coverage'] and not plan['missing_original_modules']
        assert plan['endpoint'] == config['endpoint'] and receipt['endpoints'] == [config['endpoint']]
        assert receipt['scope'] == 'EXPLICIT_EXTENSION_CLOSURE'
        assert receipt['mathlib'] == exact.PIN and receipt['leancert'] == exact.LC
        assert 'version 4.33.1,' in receipt['lean']
        assert set(receipt['modules']) == set(plan['source_sha256'])
        fresh = {name for name, row in receipt['modules'].items() if row['mode'] == 'FRESH_KERNEL_EXPORT'}
        assert fresh == config['fresh'] == set(plan['fresh_allowlist']) == set(plan['fresh_modules'])
        for name, row in receipt['modules'].items():
            assert row['module'] == name
            assert row['source_sha256'] == plan['source_sha256'][name]
            assert row['source_closure_sha256'] == plan['source_closure_sha256'][name]
            assert row['axiom_profiles'] and all(set(p) <= exact.ALLOWED for p in row['axiom_profiles'])
        print(json.dumps({
            'status': 'EXACT_ORIGINAL_CLOSED_FAMILY_CURRENT_CLOSURE_VERIFIED',
            'family': args.family, 'original_field': config['original_field'],
            'required_modules': len(receipt['modules']), 'fresh_modules': sorted(fresh),
            'original_field_scope_unchanged': True,
            'full_degree_one_large_assembly': 'PENDING_SEPARATE_THREE_MODULE_RUN',
        }), flush=True)
        return

    # Always call the existing producer, including when generated paths exist.
    # It validates both original source hashes and exact generated bytes.
    command = [sys.executable, '-B', 'ci/rg_materialize_compact_closed_families.py',
               '--endpoint', config['endpoint'], '--max-raw-mib', '512']
    subprocess.run(command, cwd=ROOT, check=True)
    hashes, dependencies, closures = exact.source_closure(config['endpoint'])
    assert len(hashes) == config['required_modules']
    assert hashes[config['endpoint']] == config['source_sha256']
    assert closures[config['endpoint']] == config['source_closure_sha256']
    groups = exact.matching_archives(hashes, closures)
    report = exact.plan(config['endpoint'], hashes, dependencies, closures, groups,
                        fresh_allowlist=config['fresh'])
    report['compact_family'] = args.family
    report['source_materialization'] = {
        'command': command, 'producer_and_registry_sha256': REGISTRIES,
        'unconditionally_validated_even_if_generated_paths_exist': True,
        'original_field': config['original_field'],
        'original_namespaces_and_theorem_bodies_unchanged': True,
        'expected_endpoint_source_sha256': config['source_sha256'],
        'expected_endpoint_source_closure_sha256': config['source_closure_sha256'],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, separators=(',', ':')) + '\n')
    print(json.dumps({
        'status': 'SEALED_COMPACT_FAMILY_RESTORE_PLANNED' if report['complete_original_object_coverage']
                  else 'MISSING_ORIGINAL_OBJECTS_NO_BULK_RESTORE',
        'family': args.family, 'endpoint': config['endpoint'],
        'required_modules': len(hashes), 'fresh_modules': report['fresh_modules'],
        'missing_original_modules': report['missing_original_modules'],
        'selected_archives': len(report['selected_archives']),
        'kernel_proof': 'NOT_PROVEN_BY_PLANNING',
    }), flush=True)
    if not report['complete_original_object_coverage']:
        raise SystemExit(2)


if __name__ == '__main__':
    main()
